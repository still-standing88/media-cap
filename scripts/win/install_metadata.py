#!/usr/bin/env python3
"""Install portable Windows development metadata and dependency/license files.

Called by every build frontend. Shared consumers need only MediaCap's import
library. Static consumers receive the actual archives used by this build.
"""
import argparse
import os
from pathlib import Path
import shutil

CODECS = ('avformat', 'avcodec', 'swscale', 'swresample', 'avutil', 'aom', 'dav1d',
          'openh264', 'opus', 'vorbisenc', 'vorbis', 'ogg', 'vpx', 'mp3lame', 'mpghip')
SYSTEM = ('dxgi d3d11 dwmapi gdi32 ws2_32 secur32 mfuuid mf mfplat mfreadwrite strmiids '
          'ole32 oleaut32 uuid user32 bcrypt kernel32 advapi32 shell32 winmm '
          'ntdll userenv dbghelp').split()

def main():
    p = argparse.ArgumentParser()
    p.add_argument('--prefix', default=os.environ.get('MESON_INSTALL_DESTDIR_PREFIX'))
    p.add_argument('--libdir', default='lib')
    p.add_argument('--bindir', default='bin')
    p.add_argument('--includedir', default='include')
    p.add_argument('--datadir', default='share')
    p.add_argument('--dependency-dir', required=True)
    p.add_argument('--shared', choices=('true', 'false'), required=True)
    p.add_argument('--debug', choices=('true', 'false'), default='false')
    p.add_argument('--rust-archive')
    a = p.parse_args()
    if os.name != 'nt':
        raise SystemExit('Portable binary packaging is currently validated for Windows only')
    root = Path(__file__).resolve().parents[2]
    prefix = Path(a.prefix)
    libdir = prefix / a.libdir
    shared = a.shared == 'true'
    debug = a.debug == 'true'
    # Meson names MSVC static archives libMediaCap.a; normalize the public
    # Windows development filename across all three frontends.
    if not shared and (libdir / 'libMediaCap.a').is_file():
        shutil.copy2(libdir / 'libMediaCap.a', libdir / 'MediaCap.lib')
        (libdir / 'libMediaCap.a').unlink()
    if not (libdir / 'MediaCap.lib').is_file():
        raise SystemExit('Missing installed MediaCap import/static library')
    if shared and not (prefix / a.bindir / 'MediaCap.dll').is_file():
        raise SystemExit('Missing installed MediaCap.dll; its name must match the import library and package metadata')
    dep_names = []
    if not shared:
        dest = libdir / 'mediacap-deps'
        dest.mkdir(parents=True, exist_ok=True)
        for name in CODECS:
            candidates = [Path(a.dependency_dir) / (pre + name + suf + '.lib')
                          for pre in ('', 'lib') for suf in ('', '-static')]
            source = next((f for f in candidates if f.is_file()), None)
            if source is None:
                raise SystemExit('Missing static dependency: ' + name)
            shutil.copy2(source, dest / source.name)
            dep_names.append('mediacap-deps/' + source.name)
        if a.rust_archive:
            rust = Path(a.rust_archive)
            shutil.copy2(rust, dest / rust.name)
            dep_names.append('mediacap-deps/' + rust.name)
            # Native frontends may also install a root-level copy. The portable
            # target links the dependency-directory copy exclusively.
            installed_alias = libdir / rust.name
            if installed_alias.is_file():
                installed_alias.unlink()
    config_dir = libdir / 'cmake/MediaCap'
    config_dir.mkdir(parents=True, exist_ok=True)
    relative_root = os.path.relpath(prefix, config_dir).replace('\\', '/')
    config = f'''# Generated by MediaCap; all package paths are relative to this file.
get_filename_component(_mc_prefix "${{CMAKE_CURRENT_LIST_DIR}}/{relative_root}" ABSOLUTE)
if(NOT TARGET MediaCap::MediaCap)
  add_library(MediaCap::MediaCap {'SHARED' if shared else 'STATIC'} IMPORTED)
  set_target_properties(MediaCap::MediaCap PROPERTIES
    INTERFACE_INCLUDE_DIRECTORIES "${{_mc_prefix}}/{a.includedir}"
    INTERFACE_COMPILE_FEATURES cxx_std_17
'''
    if shared:
        config += f'    IMPORTED_IMPLIB "${{_mc_prefix}}/{a.libdir}/MediaCap.lib"\n    IMPORTED_LOCATION "${{_mc_prefix}}/{a.bindir}/MediaCap.dll"\n'
    else:
        deps = [f'${{_mc_prefix}}/{a.libdir}/{n}' for n in dep_names] + SYSTEM
        config += (f'    IMPORTED_LOCATION "${{_mc_prefix}}/{a.libdir}/MediaCap.lib"\n'
                   f'    INTERFACE_COMPILE_DEFINITIONS MEDIACAP_STATIC\n'
                   f'    INTERFACE_LINK_LIBRARIES "{";".join(deps)}"\n')
        if debug and a.rust_archive:
            config += '    INTERFACE_LINK_OPTIONS "/NODEFAULTLIB:libcmt"\n'
    config += '  )\nendif()\nunset(_mc_prefix)\n'
    (config_dir / 'MediaCapConfig.cmake').write_text(config, encoding='utf-8')
    (config_dir / 'MediaCapConfigVersion.cmake').write_text('''set(PACKAGE_VERSION "1.0.0")
if(PACKAGE_FIND_VERSION VERSION_EQUAL PACKAGE_VERSION)
  set(PACKAGE_VERSION_EXACT TRUE)
  set(PACKAGE_VERSION_COMPATIBLE TRUE)
elseif(PACKAGE_FIND_VERSION VERSION_LESS PACKAGE_VERSION)
  set(PACKAGE_VERSION_COMPATIBLE TRUE)
endif()
''', encoding='utf-8')
    pc_dir = libdir / 'pkgconfig'
    pc_dir.mkdir(parents=True, exist_ok=True)
    relative_root = os.path.relpath(prefix, pc_dir).replace('\\', '/')
    private = ' '.join(f'"${{libdir}}/{n}"' for n in dep_names) + ' ' + ' '.join('-l' + n for n in SYSTEM) if not shared else ''
    if not shared and debug and a.rust_archive:
        private += ' /NODEFAULTLIB:libcmt'
    pc = f'''prefix=${{pcfiledir}}/{relative_root}
libdir=${{prefix}}/{a.libdir}
includedir=${{prefix}}/{a.includedir}
Name: MediaCap
Description: Screen, window, camera and audio capture
Version: 1.0.0
Libs: -L"${{libdir}}" -lMediaCap
Libs.private: {private}
Cflags: -I"${{includedir}}"{'' if shared else ' -DMEDIACAP_STATIC'}
'''
    (pc_dir / 'MediaCap.pc').write_text(pc, encoding='utf-8')
    notices = prefix / a.datadir / 'licenses/MediaCap'
    notices.mkdir(parents=True, exist_ok=True)
    for name in ('LICENSE', 'COPYING'):
        shutil.copy2(root / name, notices / name)
    if (root / 'THIRD_PARTY_NOTICES.md').is_file():
        shutil.copy2(root / 'THIRD_PARTY_NOTICES.md', notices / 'THIRD_PARTY_NOTICES.md')
    if (root / 'licenses').is_dir():
        shutil.copytree(root / 'licenses', notices / 'dependencies', dirs_exist_ok=True)
    print(f'Installed portable {"shared" if shared else "static"} package metadata at {prefix}')

if __name__ == '__main__':
    main()
